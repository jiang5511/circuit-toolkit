# ==========================================================
#  第十个程序：FFT 谐波分析（电赛 / 电能质量的看家本领）
#  场景：测到一个含谐波的电网电压信号，分析它含哪些谐波、失真多严重
# ==========================================================

import numpy as np
import matplotlib.pyplot as plt

plt.rcParams["font.sans-serif"] = ["SimHei", "Microsoft YaHei"]
plt.rcParams["axes.unicode_minus"] = False

# =========================================================
#  第一步：造一个"含谐波"的电网信号
#  真实电网里除了 50Hz 基波，还会有 3 次(150Hz)、5 次(250Hz)、7 次(350Hz)谐波
#  谐波来自变频器、整流器、LED 电源这些非线性设备
# =========================================================

fs = 5000            # 采样频率：每秒采 5000 个点
T = 1.0              # 采样时长 1 秒
N = int(fs * T)      # 总采样点数 = 5000
t = np.linspace(0, T, N, endpoint=False)

f0 = 50              # 基波频率 50 Hz

# 各次谐波的幅值（基波幅值设为 1.0，谐波按占基波的比例给）
A1, A3, A5, A7 = 1.0, 0.15, 0.08, 0.05      # 1次、3次、5次、7次

# 把信号叠加起来，再加上一点点噪声（模拟真实测量）
signal = (A1 * np.sin(2 * np.pi * f0 * t)
          + A3 * np.sin(2 * np.pi * 3 * f0 * t + 0.5)
          + A5 * np.sin(2 * np.pi * 5 * f0 * t)
          + A7 * np.sin(2 * np.pi * 7 * f0 * t)
          + 0.02 * np.random.randn(N))       # 噪声

print("=" * 55)
print("  信号参数（我偷偷设定的'标准答案'）")
print("=" * 55)
print(f"  基波 50 Hz：幅值 {A1}")
print(f"  3 次 150 Hz：幅值 {A3}")
print(f"  5 次 250 Hz：幅值 {A5}")
print(f"  7 次 350 Hz：幅值 {A7}")
print("\n下面看 FFT 能不能把它们找出来 ↓\n")

# =========================================================
#  第二步：做 FFT（快速傅里叶变换）
#  FFT 的作用：把"随时间变化的波形"翻译成"由哪些频率组成"
# =========================================================

# np.fft.rfft：对实数信号做 FFT，只返回正频率部分（省一半计算）
fft_vals = np.fft.rfft(signal)

# 频率刻度：rfftfreq(点数, 采样间隔)，第 k 个点对应 k/T Hz
freqs = np.fft.rfftfreq(N, 1 / fs)

# 幅值换算：除了直流和第 N/2 点，其余都要 ×2/N
# 这样得到的幅值才等于正弦波的真实振幅
amp = 2 * np.abs(fft_vals) / N

print("=" * 55)
print("  FFT 分析结果")
print("=" * 55)

# =========================================================
#  第三步：找出各次谐波的幅值
# =========================================================
# 做法：在目标频率附近 ±2 Hz 的范围内找最大值
# （因为频率分辨率有限，峰值可能不在整数频率上）
def find_amp(目标频率, 容差=2.0):
    mask = (freqs >= 目标频率 - 容差) & (freqs <= 目标频率 + 容差)
    return amp[mask].max()

print(f"\n  {'谐波':<8}{'频率':<10}{'FFT测得幅值':<14}{'设定值':<10}{'误差'}")
print("  " + "-" * 52)

检测 = {}
for 次数, 设定值 in zip([1, 3, 5, 7], [A1, A3, A5, A7]):
    f = 次数 * f0
    测得 = find_amp(f)
    检测[次数] = 测得
    误差 = abs(测得 - 设定值) / 设定值 * 100
    print(f"  {次数} 次{'':<4}{f:>4} Hz{'':<4}{测得:>10.4f}{'':<6}{设定值:>6.2f}{'':<5}{误差:>6.2f}%")

# =========================================================
#  第四步：算 THD（总谐波畸变率）—— 电能质量的核心指标
# =========================================================
# THD = 所有谐波的有效值 / 基波有效值 × 100%
# 国标规定：公用电网电压 THD 一般要小于 5%
谐波平方和 = sum(检测[k] ** 2 for k in [3, 5, 7])
THD = np.sqrt(谐波平方和) / 检测[1] * 100

print("\n" + "=" * 55)
print(f"  总谐波畸变率 THD = {THD:.2f}%")
if THD < 5:
    print("  → 小于 5%，符合国标要求（合格）")
else:
    print("  → 超过 5%，谐波超标！需要加滤波器")
print("=" * 55)

# =========================================================
#  第五步：画图（时域 + 频谱，两张图）
# =========================================================
plt.figure(figsize=(12, 8))

# ---- 上面：时域波形（只画前 0.08 秒，看谐波造成的畸变）----
plt.subplot(2, 1, 1)
# 只画前 400 个点（0.08 秒），太密了看不清
plt.plot(t[:400] * 1000, signal[:400], "b-", linewidth=1.5)
# 叠一条纯净的 50Hz 正弦波做对比
plt.plot(t[:400] * 1000, A1 * np.sin(2 * np.pi * f0 * t[:400]),
         "r--", linewidth=1.5, label="纯 50Hz 正弦（参考）")
plt.title("时域波形（前 80 毫秒）—— 蓝线明显不是标准正弦，已经畸变", fontsize=13)
plt.xlabel("时间（毫秒）", fontsize=12)
plt.ylabel("电压（标幺值）", fontsize=12)
plt.grid(True, linestyle=":", alpha=0.7)
plt.legend(fontsize=11)

# ---- 下面：频谱图 ----
plt.subplot(2, 1, 2)
# 只画 0~500 Hz 这一段（10 次谐波以内），关键的都在这
mask = freqs <= 500
plt.plot(freqs[mask], amp[mask], "b-", linewidth=1.5)
plt.stem([50, 150, 250, 350],
         [检测[1], 检测[3], 检测[5], 检测[7]],
         linefmt="r-", markerfmt="ro", basefmt=" ", label="检测到的谐波")

# 在峰值旁边标出幅值
for k in [1, 3, 5, 7]:
    plt.text(k * f0 + 8, 检测[k] + 0.01, f"{k}次 {检测[k]:.3f}",
             fontsize=10, color="red")

plt.title(f"频谱图（FFT）—— 总谐波畸变率 THD = {THD:.2f}%", fontsize=13)
plt.xlabel("频率（Hz）", fontsize=12)
plt.ylabel("幅值", fontsize=12)
plt.grid(True, linestyle=":", alpha=0.7)
plt.legend(fontsize=11)

plt.tight_layout()
plt.savefig("谐波分析.png", dpi=150, bbox_inches="tight")
print("\n图片已保存：谐波分析.png")
plt.show()

