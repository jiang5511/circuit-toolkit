# ==========================================================
#  第七个程序：用节点电压法解电路（电路课大题秒杀器）
#  核心：把电路写成 G × V = I，然后交给电脑解方程组
# ==========================================================

import numpy as np

print("=" * 55)
print("  节点电压法求解示例")
print("=" * 55)

# =========================================================
#  先看电路长什么样（3 个节点 + 1 个参考地）
#
#       Is1=2A          R12=5Ω          R23=10Ω
#        ↓              ┌──────┐        ┌──────┐
#    ────┴──── ● 1 ─────┤      ├─── ● 2 ┤      ├─── ● 3 ────┬────
#          │            └──────┘        │      │            │
#          │ R10=10Ω        │           │ R20  │            │ R30
#          │                │           │ =20Ω │            │ =10Ω
#          │                │           │      │            │
#         ═╧═              ═╧═         ═╧═    ═╧═          ═╧═
#          地(0V)          地           地                 地 ↑Is3=1A
#
#  已知：R10=10Ω, R12=5Ω, R20=20Ω, R23=10Ω, R30=10Ω
#        电流源 Is1 = 2 A（流入节点1），Is3 = 1 A（流入节点3）
#  求：节点电压 V1、V2、V3
# =========================================================

# ---------- 第一步：整理电路数据 ----------
# 电阻用字典记：(连接的两个节点): 电阻值
# 0 号表示"地"
resistors = {
    (1, 0): 10.0,    # R10：节点1 到地，10 Ω
    (1, 2): 5.0,     # R12：节点1 到节点2，5 Ω
    (2, 0): 20.0,    # R20：节点2 到地，20 Ω
    (2, 3): 10.0,    # R23：节点2 到节点3，10 Ω
    (3, 0): 10.0,    # R30：节点3 到地，10 Ω
}

# 电流源：注入节点的电流（流入为正，流出为负）
current_sources = {
    1: 2.0,          # 2 A 流入节点1
    3: 1.0,          # 1 A 流入节点3
}

n = 3               # 未知节点数（节点 1、2、3）

# ---------- 第二步：建立电导矩阵 G ----------
# 电导 = 1 / 电阻，单位西门子 S
# 节点电压法的规律（记住这三条就够了）：
#   1. 对角线 G[i][i] = 所有连到节点 i 的电导之和（全为正）
#   2. 非对角线 G[i][j] = 节点 i、j 之间电导的相反数（全为负）
#   3. 没有直接相连的两个节点，填 0
G = np.zeros((n, n))          # 先造一个全 0 的 3×3 矩阵

for (a, b), R in resistors.items():
    g = 1 / R                 # 电导
    if a != 0:                # 0 是地，不参与方程
        G[a-1, a-1] += g      # 对角线加上这个电导（Python 下标从 0 开始，所以 a-1）
    if b != 0:
        G[b-1, b-1] += g
    if a != 0 and b != 0:     # 两个都不是地 → 填互电导（负的）
        G[a-1, b-1] -= g
        G[b-1, a-1] -= g

print("\n【电导矩阵 G】（单位 S）")
print(np.round(G, 4))

# ---------- 第三步：建立电流向量 I ----------
I = np.zeros(n)
for node, Is in current_sources.items():
    I[node-1] = Is            # 流入为正

print("\n【电流向量 I】（单位 A）")
print(I)

# ---------- 第四步：解方程组 G × V = I ----------
# np.linalg.solve(A, b) 就是解 Ax = b，一行搞定
V = np.linalg.solve(G, I)

print("\n" + "=" * 55)
print("【节点电压解】")
for i in range(n):
    print(f"  V{i+1} = {V[i]:.4f} V")
print("=" * 55)

# ---------- 第五步：算各支路电流，并验证 KCL ----------
print("\n【各支路电流】（正号表示从第一个节点流向第二个）")
for (a, b), R in resistors.items():
    Ua = 0.0 if a == 0 else V[a-1]     # 地的电压是 0
    Ub = 0.0 if b == 0 else V[b-1]
    I_branch = (Ua - Ub) / R           # 欧姆定律
    print(f"  R{a}{b} = {R:>5.1f} Ω → I = ({Ua:.3f} - {Ub:.3f}) / {R} = {I_branch:>7.4f} A")

# KCL 校验：每个节点流出的电流之和，应该等于注入的电流
print("\n【KCL 校验】（流出总和 应等于 注入电流）")
for i in range(1, n+1):
    out = 0.0
    for (a, b), R in resistors.items():
        Ua = 0.0 if a == 0 else V[a-1]      # 地的电压算 0
        Ub = 0.0 if b == 0 else V[b-1]
        if a == i:                           # 电流从节点 i 流向对方
            out += (Ua - Ub) / R
        elif b == i:                         # 电流从对方流向节点 i（对"流出"来说是负的）
            out += (Ub - Ua) / R
    inject = current_sources.get(i, 0.0)
    ok = "OK" if abs(out - inject) < 1e-9 else "不对"
    print(f"  节点{i}：净流出 {out:.6f} A，注入 {inject:.6f} A，"
          f"误差 {abs(out - inject):.2e}  {ok}")

# =========================================================
#  重要提示：遇到"电压源串联电阻"怎么办？
#  答：等效变换成电流源，公式为  Is = Us / R
#  例：10V 电压源串 5Ω 电阻接到节点1 → 等效为 2A 电流源注入节点1
#  这样就能统一用上面的方法解了（这一步叫"电源等效变换"）
