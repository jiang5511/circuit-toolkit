# ==========================================================
#  LED 限流电阻计算器（进硬件部第一个用得上的工具）
#  你只要回答问题，它算出该用多大的电阻、多大功率、色环是什么
# ==========================================================

print("=" * 58)
print("  LED 限流电阻计算器")
print("=" * 58)

# ---------- 常用 LED 的正向压降（单位 V）----------
# 不同颜色的 LED，导通时"吃掉"的电压不一样
LED_压降表 = {
    "红色": 1.9,
    "黄色": 2.1,
    "绿色": 2.1,
    "蓝色": 3.2,
    "白色": 3.2,
    "翠绿": 3.2,
}

print("\n常见 LED 的正向压降：")
for name, v in LED_压降表.items():
    print(f"  {name}：{v} V")

# ---------- 输入参数 ----------
print("\n----- 请回答几个问题 -----")

U_power = float(input("\n1. 电源电压是多少 V？（常见 5 / 3.3 / 12）\n   → "))

print("\n2. LED 是什么颜色？")
print("   直接输入颜色（红/黄/绿/蓝/白/翠绿），或直接输入压降数值")
yanse = input("   → ")

# 判断用户输入的是颜色名还是数字
if yanse in LED_压降表:
    U_led = LED_压降表[yanse]
    print(f"   已选定：{yanse} LED，压降 {U_led} V")
else:
    U_led = float(yanse)
    print(f"   已设定压降：{U_led} V")

I_mA = float(input("\n3. 想让每个 LED 流过多大电流 mA？（指示灯常用 10~20）\n   → "))
n_series = int(input("\n4. 每串串联几个 LED？（一般填 1）\n   → "))
n_branch = int(input("\n5. 有几条并联支路？（一般填 1）\n   → "))

# ---------- 开始计算 ----------
I = I_mA / 1000                    # mA 换算成 A
U_left = U_power - n_series * U_led    # 电阻上需要分掉的电压

print("\n" + "=" * 58)
print("  计算结果")
print("=" * 58)

# 先检查电压够不够
if U_left <= 0:
    print(f"\n❌ 电压不够！")
    print(f"   {n_series} 个 LED 串联需要至少 {n_series * U_led:.1f} V")
    print(f"   但你只有 {U_power} V")
    print(f"   建议：把串联个数减到 {int(U_power // U_led)} 个，或换更高电压")
else:
    R_theory = U_left / I          # 理论电阻值 = 剩余电压 ÷ 电流

    # ---------- 找最接近的"标准阻值" ----------
    # 电阻不是想要多大就有多大，厂家只生产固定的一串值（E24 系列）
    E24 = [1.0, 1.1, 1.2, 1.3, 1.5, 1.6, 1.8, 2.0, 2.2, 2.4, 2.7,
           3.0, 3.3, 3.6, 3.9, 4.3, 4.7, 5.1, 5.6, 6.2, 6.8, 7.5,
           8.2, 9.1]

    # 造出所有可能的标准阻值（1Ω 到 10MΩ）
    标准值 = []
    for bei in [1, 10, 100, 1000, 10000, 100000, 1000000]:
        for v in E24:
            标准值.append(v * bei)

    # 选一个"不小于理论值"的最小标准值（往大取，保证电流不超过 LED 承受范围）
    R_std = min([r for r in 标准值 if r >= R_theory])

    # ---------- 算实际电流和功率 ----------
    I_actual = U_left / R_std                  # 用标准阻值后的真实电流
    P = I_actual ** 2 * R_std                  # 电阻上消耗的功率

    print(f"\n  理论电阻值：{R_theory:.1f} Ω")
    print(f"  ➜ 应选用标准值：{R_std:.0f} Ω  ({R_std/1000:.3f} kΩ)" if R_std >= 1000
          else f"  ➜ 应选用标准值：{R_std:.0f} Ω")

    print(f"\n  实际工作电流：{I_actual*1000:.2f} mA")
    print(f"  电阻消耗功率：{P*1000:.1f} mW（{P:.4f} W）")

    # 功率要留 2 倍余量，不然电阻会烫
    if P * 2 <= 0.25:
        print("  ➜ 选 1/4 W 普通电阻即可（余量充足）")
    elif P * 2 <= 0.5:
        print("  ➜ 建议选 1/2 W 电阻")
    else:
        print("  ➜ 功率较大，需要 1 W 以上电阻或改用恒流驱动")

    # ---------- 总电流 ----------
    I_total = I_actual * n_branch
    print(f"\n  共 {n_branch} 条支路 → 总电流约 {I_total*1000:.1f} mA")
    if n_branch > 1:
        print("  注意：每条支路都要各自串一个电阻，不能共用一个！")

    # ---------- 色环 ----------
    颜色 = ["黑", "棕", "红", "橙", "黄", "绿", "蓝", "紫", "灰", "白"]
    倍率色 = {0: "黑", 1: "棕", 2: "红", 3: "橙", 4: "黄", 5: "绿", 6: "蓝"}

    # 把阻值拆成"两位有效数字 × 10 的几次方"
    m, e = R_std, 0
    while m >= 100:
        m /= 10
        e += 1
    while m < 10:
        m *= 10
        e -= 1
    m = round(m)
    if m >= 100:
        m /= 10
        e += 1
    d1, d2 = int(m // 10), int(m % 10)

    if e in 倍率色:
        print(f"\n  色环（四环）：{颜色[d1]} {颜色[d2]} {倍率色[e]} 金")
        print(f"  即：{d1} {d2} × 10^{e} = {R_std:.0f} Ω，误差 ±5%")
    else:
        print(f"\n  色环（四环）：{颜色[d1]} {颜色[d2]} 金 金（{R_std:.1f} Ω）")

    # ---------- 接线提示 ----------
    print("\n" + "-" * 58)
    print("  接线方法：")
    print(f"    电源 {U_power}V 正极 → 电阻({R_std:.0f} Ω) → LED正极(长脚)")
    print(f"    LED负极(短脚) → 电源负极(GND)")
    print("  ⚠️ 通电前确认：LED 长脚接正极，电阻串在回路里")
    print("-" * 58)
