# ==========================================================
#  第四个程序：电阻串并联 + 分压分流计算器
#  用途：做电路实验时，不用按计算器，直接出结果
# ==========================================================

print("===== 电阻串并联计算器 =====\n")

# ---------- 第一步：让用户输入电阻 ----------
# 提示用户用空格隔开输入多个电阻，例如：100 200 300
shuru = input("请输入所有电阻值（用空格隔开，例如：100 200 300）：")

# split() 会把 "100 200 300" 拆成 ["100", "200", "300"]
# float(x) 把每个字符串变成小数
# [ ... for x in ... ] 叫"列表推导式"，作用就是：把一批东西逐个处理，凑成一个列表
R_list = [float(x) for x in shuru.split()]

# ---------- 第二步：输入总电压 ----------
U = float(input("请输入总电压 U（单位 V）："))

# 检查一下有没有填 0（电阻为 0 会让后面除以 0 报错）
if 0 in R_list:
    print("错误：电阻不能为 0！")
else:
    print(f"\n你输入了 {len(R_list)} 个电阻：{R_list} Ω\n")

    # ================= 串联 =================
    # 串联总电阻 = 全部相加
    # sum() 是 Python 自带的求和函数
    R_chuan = sum(R_list)

    print("=" * 45)
    print("【串联】")
    print(f"总电阻 R = {' + '.join(str(r) for r in R_list)} = {R_chuan:.2f} Ω")

    # 串联分压：每个电阻分到的电压 = 总电压 × (自己的电阻 / 总电阻)
    # 这是分压公式：电阻越大，分到的电压越多
    print("\n各电阻分到的电压：")
    for i, R in enumerate(R_list, start=1):
        U_i = U * R / R_chuan
        zhan_bi = R / R_chuan * 100         # 这个电阻占总电阻的百分比
        print(f"  R{i} = {R:>8.2f} Ω  →  电压 {U_i:>7.3f} V（占 {zhan_bi:.1f}%）")

    # ================= 并联 =================
    # 并联总电阻：1/R = 1/R1 + 1/R2 + ...
    # 所以要先算出倒数的和，再取倒数
    dao_shu_he = sum(1 / R for R in R_list)
    R_bing = 1 / dao_shu_he

    print("\n" + "=" * 45)
    print("【并联】")
    print(f"总电阻 R = 1 / (1/R1 + 1/R2 + ...) = {R_bing:.4f} Ω")

    # 并联分流：各支路电压相同，所以 I_i = U / R_i
    # 总电流 = 各支路电流之和（基尔霍夫电流定律）
    print("\n各支路电流：")
    I_zong = 0
    for i, R in enumerate(R_list, start=1):
        I_i = U / R
        I_zong += I_i          # += 的意思是"自己加上后面的数"
        print(f"  R{i} = {R:>8.2f} Ω  →  电流 {I_i:>9.5f} A（{I_i*1000:>8.3f} mA）")
    print(f"  总电流 I = {I_zong:.5f} A")

    # 验证一下：总电流 = U / 总电阻，两种方法算出来应该一样
    print(f"  验证：U / R总 = {U / R_bing:.5f} A（和上面应该一致）")

    print("\n" + "=" * 45)
    print("小结：")
    print(f"  串联 → 电阻越串越大（{R_chuan:.2f} Ω）")
    print(f"  并联 → 电阻越并越小（{R_bing:.4f} Ω），比最小的那个还小")
